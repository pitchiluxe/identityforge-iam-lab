const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
fs.mkdirSync(path.join(__dirname, '../../tmp'), { recursive: true });
(async () => {
 const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5188'], { cwd: path.join(__dirname,'..'), windowsHide:true });
 let browser;
 try {
  await new Promise((resolve,reject) => { server.stdout.on('data', d => { if(d.toString().includes('Local:')) resolve(); }); server.on('error',reject); setTimeout(()=>reject(Error('Server timeout')),15000).unref(); });
  browser = await chromium.launch({ headless:true });
  const page = await browser.newPage({ viewport:{width:1440,height:1000} });
  await page.goto('http://127.0.0.1:5188/');
  const result = await page.evaluate(async () => {
      const { store } = await import('/src/ui/store.ts');
      const { openFile } = await import('/src/ui/launch.ts'); document.querySelector('.lk')?.remove(); const { initWm } = await import('/src/ui/wm.ts'); initWm(document.body.appendChild(Object.assign(document.createElement('div'), {style:'position:fixed;inset:0'})), document.body.appendChild(document.createElement('div')), []);
      const { writeFile, homeDir, ensureSamplePdfs } = await import('/src/world/docs.ts');
      const { parsePdf } = await import('/src/core/pdfdoc.ts');
      const assert = (v, msg) => { if (!v) throw new Error(msg); };
      const file = homeDir(store.world) + '\\Documents\\lab-editor-smoke.ps1';
      writeFile(store.world, file, '# LAB-001\nGet-ADUser -Filter *');
      openFile(file, 'notepadpp');
      const ta = document.querySelector('.npp-ta');
      assert(ta && ta.value.includes('Get-ADUser'), 'Notepad++ opens lab scripts');
      ta.value += '\n# saved from editor'; ta.dispatchEvent(new Event('input', { bubbles: true }));
      document.querySelector('.npp [aria-label="Save"]').click();
      assert(store.world.files.find(f => f.path === file).content.includes('saved from editor'), 'Notepad++ saves edits');
      document.querySelector('.npp [aria-label="Find"]').click();
      assert(document.querySelector('.npp [role="dialog"]'), 'Notepad++ Find opens');
      ensureSamplePdfs(store.world); const pdf = store.world.files.find(f => /\.pdf$/i.test(f.path) && !f.deleted);
      assert(pdf, 'Sample PDF is available'); openFile(pdf.path);
      assert(document.querySelector('.pdx'), 'PDF editor opens');
      assert(document.querySelector('.pdx-doctabs').textContent.includes(pdf.path.split('\\').pop()), 'PDF tab names the document');
      assert(document.querySelector('.pdx-view').textContent.trim().length > 20, 'PDF page renders text');
      const before = parsePdf(pdf.content);
      assert(before.pages.length > 0, 'Sample PDF has pages');
      document.querySelector('.npp [role="dialog"] [aria-label="Close"]').click();
      const form = document.querySelector('.pdx-ftext'); form.value = 'LAB-001'; form.dispatchEvent(new Event('change', {bubbles:true}));
      document.querySelector('.pdx').dispatchEvent(new KeyboardEvent('keydown', {key:'s',ctrlKey:true,bubbles:true}));
      assert(parsePdf(store.world.files.find(f => f.path === pdf.path).content).fields.some(f => f.value === 'LAB-001'), 'PDF form saves to virtual disk');
      const target = homeDir(store.world) + '\\Documents\\existing.pdf'; writeFile(store.world, target, pdf.content);
      const root = document.querySelector('.pdx');
      root.dispatchEvent(new KeyboardEvent('keydown', {key:'n',ctrlKey:true,bubbles:true}));
      root.dispatchEvent(new KeyboardEvent('keydown', {key:'s',ctrlKey:true,shiftKey:true,bubbles:true}));
      root.querySelector('[aria-label="File name"]').value = 'existing.pdf';
      [...root.querySelectorAll('.pdx-dlg-btns button')].find(b => b.textContent === 'Save').click();
      await new Promise(r => setTimeout(r, 30));
      const overwriteGuard = !!root.querySelector('[role="dialog"][aria-label="Confirm Save As"]');
      const oldPreserved = store.world.files.find(f => f.path === target).content === pdf.content;
      const no = [...root.querySelectorAll('.pdx-dlg-btns button')].find(b => b.textContent === 'No'); if (no) no.click();
      root.closest('.win').querySelector('.cap.close').click();
      const closeGuard = !!document.querySelector('.pdx [role="dialog"]');
      assert(overwriteGuard && oldPreserved, 'Save As must confirm before replacing an existing PDF');
      assert(closeGuard, 'Closing an unsaved PDF window must prompt');
      [...root.querySelectorAll('.pdx-dlg-btns button')].find(b => b.textContent === 'Cancel').click(); openFile(pdf.path);
      return { overwriteGuard, closeGuard, notepadSave: true, notepadFind: true, pdfOpen: true, pdfPages: before.pages.length, pdfText: document.querySelector('.pdx-view').textContent.slice(0, 250) };
    });
  fs.writeFileSync(path.join(__dirname,'../../tmp/editor-ui-smoke.json'),JSON.stringify(result,null,2));
  await page.waitForTimeout(350);
  await page.screenshot({path:path.join(__dirname,'../../tmp/editor-ui-smoke.png')});
  console.log(result);
 } finally { if(browser) await browser.close(); server.kill(); }
})().catch(e => {console.error(e);process.exitCode=1;});
