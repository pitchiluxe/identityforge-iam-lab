/** Isolated browser regression checks; run with node tests/azure-ui.cjs. */
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
(async () => {
  const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5192', '--strictPort'], { cwd: path.join(__dirname, '..'), windowsHide: true });
  let browser;
  try {
    await new Promise((resolve, reject) => { server.stdout.on('data', d => { if (d.toString().includes('Local:')) resolve(); }); server.on('error', reject); server.on('exit', code => reject(Error(`Preview exited: ${code}`))); setTimeout(() => reject(Error('Preview timeout')), 15000).unref(); });
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.goto('http://127.0.0.1:5192/');
    const result = await page.evaluate(async () => {
      const { createCompanyWorld, MSP_ADMIN } = await import('/src/world/mspSeed.ts');
      const { profileById } = await import('/src/world/profiles.ts');
      const groups = await import('/src/world/entraAdmin.ts');
      const apps = await import('/src/world/apps.ts');
      const { entraGroupPage, entraPage } = await import('/src/ui/sites/azure/entra.ts');
      const { appRegPage } = await import('/src/ui/sites/azure/apps.ts');
      const { setClock } = await import('/src/core/time.ts');
      setClock(() => Date.parse('2026-10-30T12:00:00Z'));
      const w = createCompanyWorld(profileById('kestrel'));
      const me = `${MSP_ADMIN}@${w.entra.primaryDomain}`;
      const u = groups.createCloudUser(w, me, { displayName: 'LAB Owner', mailNickname: 'lab-owner', password: 'Lab-Only!2026', forceChange: true });
      const g = groups.createCloudGroup(w, me, { name: 'lab-project', description: '', type: 'Security', owners: [] });
      const r = apps.registerApp(w, me, { name: 'LAB Client', redirectUris: [] });
      document.body.replaceChildren();
      const host = document.body.appendChild(document.createElement('main'));
      host.className = 'az-content';
      let render = () => entraGroupPage(p, g.name);
      let error = '';
      const p = { w, domain: w.ad.domain, upn: me, ctx: {}, go: () => draw(), run: fn => { try { fn(w, p.upn); error = ''; draw(); return true; } catch (e) { error = e.message; return false; } } };
      const draw = () => host.replaceChildren(render());
      const assert = (v, msg) => { if (!v) throw Error(msg); };
      const field = label => { const el = host.querySelector(`[aria-label="${label}"]`); assert(el, `Missing control: ${label}`); return el; };
      const click = text => { const el = [...host.querySelectorAll('button')].find(b => b.textContent === text); assert(el, `Missing button: ${text}`); el.click(); };
      draw();
      field('Group description').value = 'Lab project access'; click('Save properties');
      assert(g.description === 'Lab project access', 'Group properties save');
      field('Group owner').value = u.upn; click('Add owner');
      assert(g.owners.includes(u.upn), 'Group owner added');
      host.querySelector(`[aria-label="Remove group owner ${u.upn}"]`).click();
      assert(!g.owners.includes(u.upn), 'Group owner removed');
      render = () => appRegPage(p, r.appId); draw();
      field('Application owner').value = u.upn; click('Add owner');
      assert(r.owners.includes(u.upn), 'Application owner added');
      field('Redirect URIs').value = 'https://lab-app.invalid/Callback\nhttp://localhost:5173/'; click('Save redirect URIs');
      assert(r.redirectUris.length === 2, 'Redirect URLs save');
      field('Redirect URIs').value = 'javascript:alert(1)'; click('Save redirect URIs');
      assert(error && r.redirectUris.length === 2, 'Invalid URLs do not change saved settings');
      w.entra.signIns.push({ id: 'lab-signin', time: '2026-10-30T12:00:00Z', upn: u.upn, app: 'LAB Client', ip: '203.0.113.5', location: 'Lab', device: 'LAB-PC', result: 'Failure', failureReason: 'AADSTS50011', mfa: 'Not required', ca: '', risk: 'none' });
      render = () => entraPage(p, 'signins'); draw();
      field('Search logs').value = 'AADSTS50011'; click('Apply filters');
      assert(host.textContent.includes('AADSTS50011') && host.querySelectorAll('tbody tr').length === 1, 'Sign-in filtering');
      field('Search logs').value = 'no-such-event'; click('Apply filters');
      assert(host.textContent.includes('No matching events'), 'Explicit empty result'); click('Clear filters');
      assert(host.textContent.includes('AADSTS50011'), 'Clear restores sign-ins');
      render = () => entraPage(p, 'audit'); draw();
      field('Search logs').value = 'lab-project'; click('Apply filters');
      assert(host.textContent.includes('Add owner to group'), 'Audit search finds new changes');
      return { groupProperties: true, groupOwners: true, appOwners: true, redirectUris: true, invalidUrlsRejected: true, signInFilters: true, auditFilters: true };
    });
    const output = path.join(__dirname, '../../tmp'); fs.mkdirSync(output, { recursive: true });
    fs.writeFileSync(path.join(output, 'azure-ui.json'), JSON.stringify(result, null, 2));
    await page.screenshot({ path: path.join(output, 'azure-ui.png') });
    console.log(result);
  } finally { if (browser) await browser.close(); server.kill(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
